// src/blogPage.js
export function renderBlog(container) {
  document.body.style.overflow = "";

  const articles = [
    {
      title: "То, что не расскажут на регрессии",
      date: "2026-04-15",
      text: `
        <p>Большинство людей слышали про «путешествие в прошлую жизнь». Но за этим феноменом скрывается несколько фактов, от которых по-настоящему захватывает дух.</p>

        <h4>Майкл Ньютон открыл это случайно</h4>
        <p>Доктор Майкл Ньютон был убеждённым скептиком. Годами он отказывался работать с прошлыми жизнями, считая это ненаучным. Но в 1968 году, работая с женщиной с тяжёлой депрессией, он случайно ввёл её в состояние глубже обычного гипноза — и она оказалась не в прошлой жизни, а <em>между жизнями</em>. Она описала своих «друзей по душе» — группу существ, с которыми была связана через воплощения. После этого сеанса её депрессия прошла. За 35 лет практики Ньютон провёл более 7&thinsp;000 таких сессий — и все пациенты, независимо друг от друга, описывали одно и то же пространство.</p>

        <h4>Дети и взрослые помнят по-разному</h4>
        <p>Вот деталь, которую почти никто не замечает: у детей, спонтанно вспоминающих прошлую жизнь, между смертью предыдущей личности и новым рождением проходит в среднем 2 года. У взрослых в гипнотической регрессии этот интервал неожиданно вырастает — до ста лет и более. Почему — никто пока не знает.</p>

        <h4>Родимые пятна и раны прошлого</h4>
        <p>Исследователи фиксируют один и тот же паттерн: родимые пятна у детей нередко совпадают с ранениями из предыдущей жизни. Доктор Ян Стивенсон из Университета Вирджинии задокументировал более 2&thinsp;500 таких случаев — это крупнейшая в мире база данных по спонтанным воспоминаниям о реинкарнации.</p>

        <h4>В Тибете за это дают наследство</h4>
        <p>Малоизвестный юридический факт: в Тибете доказанный случай реинкарнации даёт право на наследование имущества человека из предыдущего воплощения. Это не религиозный ритуал — это официальная правовая практика, существующая веками.</p>

        <h4>Что происходит на самом деле</h4>
        <p>Ньютон описывал несколько уровней глубины транса. На поверхностном человек видит прошлые жизни. На более глубоком — попадает в пространство между жизнями, где встречает свою «группу душ», наставника и просматривает план текущего воплощения. Примечательно: сам Ньютон не верил в реинкарнацию. Данные заставили его изменить взгляды — не наоборот.</p>

        <p class="blog-quote">«Регрессия — это не ответы. Это вопросы, которые ты начинаешь задавать себе по-новому.»</p>
      `,
    },
    {
      title: "Исцеляющее дыхание",
      date: "2025-11-06",
      text: `<p>Техника полного йоговского дыхания позволяет снять тревожность и вернуть ясность мышления. Попробуй практиковать утром или вечером — эффект проявится почти сразу.</p>`,
    },
    {
      title: "Медитация на звёздное небо",
      date: "2025-11-01",
      text: `<p>Сосредоточься на изображении звёздного неба и позволь своему разуму раствориться среди космических огней. Это помогает отпустить суету дня и обрести спокойствие перед сном.</p>`,
    },
    {
      title: "Поток мысли",
      date: "2025-10-29",
      text: `<p>Не мешай мыслям идти своим чередом — наблюдай, как внутренний диалог рассеивается и уступает место глубинному покою.</p>`,
    },
  ];

  let activeIdx = 0;

  function formatDate(dateStr) {
    const d = new Date(dateStr);
    return d.toLocaleDateString("ru-RU", {
      day: "numeric",
      month: "long",
      year: "numeric",
    });
  }

  function render() {
    container.innerHTML = `
      <section class="blog-main-layout">
        <aside class="blog-list-menu">
          <ul>
            ${articles
              .map(
                (a, i) => `
              <li class="blog-menu-item${i === activeIdx ? " active" : ""}" data-idx="${i}">
                <span class="blog-menu-title">${a.title}</span>
                <span class="blog-menu-date">${formatDate(a.date)}</span>
              </li>`,
              )
              .join("")}
          </ul>
        </aside>
        <div class="blog-article-viewport">
          <article class="blog-card">
            <div class="blog-date">${formatDate(articles[activeIdx].date)}</div>
            <h3 class="blog-card-title">${articles[activeIdx].title}</h3>
            <div class="blog-card-text">${articles[activeIdx].text}</div>
          </article>
        </div>
      </section>
    `;

    container.querySelectorAll(".blog-menu-item").forEach((item) => {
      item.addEventListener("click", () => {
        activeIdx = Number(item.dataset.idx);
        render();
      });
    });
  }

  render();

  return function cleanup() {
    document.body.style.overflow = "";
  };
}
